function strings(lang, siteSub, key) {
  const table = COMMON[lang] || COMMON.en;
  if (key in table) return table[key];
  const site = SITE_LABELS[siteSub];
  if (site && site[lang] && key in site[lang]) return site[lang][key];
  if (site && site.en && key in site.en) return site.en[key];
  return key;
}

